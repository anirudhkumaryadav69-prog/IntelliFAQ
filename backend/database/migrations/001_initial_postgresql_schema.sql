-- =============================================================================
-- IntelliFAQ 2.0 — Initial PostgreSQL / Supabase Migration (Schema v5)
-- File: backend/database/migrations/001_initial_postgresql_schema.sql
--
-- Purpose:
--   Establishes the PostgreSQL schema equivalent to SQLite SCHEMA_VERSION = 5
--   defined in backend/database/db.py, with PostgreSQL-native types, identity
--   columns, JSONB, TIMESTAMPTZ, case-insensitive unique indexes, and Row Level
--   Security (RLS) enabled for Supabase deployment.
--
-- Notes:
--   - Does NOT modify or drop existing data.
--   - Designed to be idempotent for initial schema provisioning.
--   - Designed for server-side Flask access via direct PostgreSQL connection
--     (owner / service role) while blocking anonymous Supabase Data API access.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 0. Schema Migration Tracking (replaces SQLite PRAGMA user_version)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS schema_migrations (
    version     INTEGER PRIMARY KEY,
    description TEXT NOT NULL,
    applied_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- 1. Conversations & Messages (Persistent Chat + Clarification State)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS conversations (
    conversation_id        TEXT PRIMARY KEY
                           CHECK (char_length(conversation_id) = 36),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_resolved_faq_id   BIGINT,
    last_resolved_question TEXT,
    last_resolved_category TEXT,
    pending_candidates     JSONB NOT NULL DEFAULT '[]'::jsonb,
    clarification_state    JSONB NOT NULL DEFAULT '{}'::jsonb,
    title                  TEXT NOT NULL DEFAULT 'New Conversation',
    is_title_custom        BOOLEAN NOT NULL DEFAULT FALSE,
    is_active              BOOLEAN NOT NULL DEFAULT TRUE,
    last_activity_seq      BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_conversations_created_at
    ON conversations (created_at);

CREATE INDEX IF NOT EXISTS idx_conversations_activity
    ON conversations (is_active, last_activity_seq);

CREATE TABLE IF NOT EXISTS messages (
    message_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id       TEXT NOT NULL
                          REFERENCES conversations(conversation_id)
                          ON DELETE CASCADE,
    role                  TEXT NOT NULL
                          CHECK (role IN ('user', 'assistant')),
    message_text          TEXT NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    match_type            TEXT
                          CHECK (match_type IS NULL OR match_type IN
                                 ('clear_match', 'ambiguous_match', 'no_reliable_match')),
    category              TEXT,
    faq_id                BIGINT,
    confidence            DOUBLE PRECISION,
    is_multi_intent       BOOLEAN NOT NULL DEFAULT FALSE,
    matched_question      TEXT,
    fallback              BOOLEAN NOT NULL DEFAULT FALSE,
    needs_clarification   BOOLEAN NOT NULL DEFAULT FALSE,
    clarification_message TEXT,
    candidates            JSONB NOT NULL DEFAULT '[]'::jsonb,
    sub_responses         JSONB NOT NULL DEFAULT '[]'::jsonb,
    reply_to_message_id   BIGINT
                          REFERENCES messages(message_id)
                          ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_messages_conversation_created
    ON messages (conversation_id, created_at, message_id);

CREATE INDEX IF NOT EXISTS idx_messages_reply_to
    ON messages (reply_to_message_id);

-- -----------------------------------------------------------------------------
-- 2. Admin Authentication & Session Security
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin_users (
    admin_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Replaces SQLite `UNIQUE COLLATE NOCASE`
CREATE UNIQUE INDEX IF NOT EXISTS uq_admin_users_username_lower
    ON admin_users (LOWER(username));

CREATE TABLE IF NOT EXISTS admin_sessions (
    session_id TEXT PRIMARY KEY,
    admin_id   BIGINT NOT NULL
               REFERENCES admin_users(admin_id)
               ON DELETE CASCADE,
    csrf_token TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_sessions_expires
    ON admin_sessions (expires_at);

CREATE INDEX IF NOT EXISTS idx_admin_sessions_admin_id
    ON admin_sessions (admin_id);

-- -----------------------------------------------------------------------------
-- 3. FAQ Knowledge Base (Categories, FAQs, Alternative Phrasings)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS faq_categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Replaces SQLite `UNIQUE COLLATE NOCASE`
CREATE UNIQUE INDEX IF NOT EXISTS uq_faq_categories_name_lower
    ON faq_categories (LOWER(name));

CREATE TABLE IF NOT EXISTS faqs (
    faq_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL
                REFERENCES faq_categories(category_id)
                ON DELETE RESTRICT,
    question    TEXT NOT NULL,
    answer      TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_faqs_category
    ON faqs (category_id);

CREATE TABLE IF NOT EXISTS faq_alternatives (
    alt_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faq_id     BIGINT NOT NULL
               REFERENCES faqs(faq_id)
               ON DELETE CASCADE,
    question   TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_faq_alternatives_faq
    ON faq_alternatives (faq_id);

-- -----------------------------------------------------------------------------
-- 4. Unanswered Questions & Admin Activity Audit Log
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS unanswered_questions (
    item_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_text       TEXT NOT NULL,
    conversation_id  TEXT,
    match_type       TEXT NOT NULL
                     CHECK (match_type IN ('no_reliable_match', 'ambiguous_match')),
    occurrence_count INTEGER NOT NULL DEFAULT 1,
    status           TEXT NOT NULL DEFAULT 'unreviewed'
                     CHECK (status IN ('unreviewed', 'reviewed', 'resolved', 'dismissed')),
    review_notes     TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_unanswered_status_updated
    ON unanswered_questions (status, updated_at);

CREATE TABLE IF NOT EXISTS admin_activity_log (
    activity_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action       TEXT NOT NULL,
    entity_type  TEXT NOT NULL,
    entity_label TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- 5. Official University Document Knowledge Base & Chunks
--    Binary files are stored in private Supabase Storage bucket
--    `intellifaq-documents`; `storage_filename` stores the object key.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS documents (
    document_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             TEXT NOT NULL,
    doc_type          TEXT NOT NULL,
    academic_year     TEXT NOT NULL,
    department        TEXT,
    description       TEXT,
    effective_date    DATE,
    expiry_date       DATE,
    original_filename TEXT NOT NULL,
    storage_filename  TEXT NOT NULL,
    mime_type         TEXT NOT NULL,
    file_size         BIGINT NOT NULL,
    sha256_hash       TEXT NOT NULL,
    version           INTEGER NOT NULL DEFAULT 1,
    superseded_by_id  BIGINT
                      REFERENCES documents(document_id)
                      ON DELETE SET NULL,
    page_count        INTEGER,
    chunk_count       INTEGER NOT NULL DEFAULT 0,
    extracted_preview TEXT,
    processing_status TEXT NOT NULL DEFAULT 'uploaded'
                      CHECK (processing_status IN ('uploaded', 'processing', 'processed', 'failed', 'OCR_REQUIRED', 'archived')),
    approval_status   TEXT NOT NULL DEFAULT 'pending_review'
                      CHECK (approval_status IN ('pending_review', 'approved', 'rejected')),
    uploaded_by       TEXT NOT NULL,
    error_message     TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_documents_status
    ON documents (processing_status, approval_status);

CREATE INDEX IF NOT EXISTS idx_documents_sha256
    ON documents (sha256_hash);

CREATE TABLE IF NOT EXISTS document_chunks (
    chunk_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT NOT NULL
                    REFERENCES documents(document_id)
                    ON DELETE CASCADE,
    chunk_index     INTEGER NOT NULL,
    page_number     INTEGER,
    section_heading TEXT,
    paragraph_ref   TEXT,
    chunk_text      TEXT NOT NULL,
    char_count      INTEGER NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_document_chunks_doc
    ON document_chunks (document_id, chunk_index);

CREATE TABLE IF NOT EXISTS document_processing_logs (
    log_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL
                REFERENCES documents(document_id)
                ON DELETE CASCADE,
    event_type  TEXT NOT NULL,
    status      TEXT NOT NULL,
    message     TEXT NOT NULL,
    actor       TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_document_logs_doc
    ON document_processing_logs (document_id, log_id);

-- -----------------------------------------------------------------------------
-- 6. Record Baseline Schema Version (matches SQLite SCHEMA_VERSION = 5)
-- -----------------------------------------------------------------------------
INSERT INTO schema_migrations (version, description)
VALUES (5, 'Initial PostgreSQL schema matching IntelliFAQ 2.0 SQLite v5')
ON CONFLICT (version) DO NOTHING;

-- -----------------------------------------------------------------------------
-- 7. Supabase Row Level Security (RLS) & Privilege Hardening
--    Enabling RLS with zero anon/authenticated policies blocks all direct
--    Supabase Data API (PostgREST) reads/writes while preserving full access
--    for the Flask backend's server-side PostgreSQL connection.
-- -----------------------------------------------------------------------------
ALTER TABLE schema_migrations        ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversations            ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages                 ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_users              ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_sessions           ENABLE ROW LEVEL SECURITY;
ALTER TABLE faq_categories           ENABLE ROW LEVEL SECURITY;
ALTER TABLE faqs                     ENABLE ROW LEVEL SECURITY;
ALTER TABLE faq_alternatives         ENABLE ROW LEVEL SECURITY;
ALTER TABLE unanswered_questions     ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_activity_log       ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents                ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_chunks          ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_processing_logs ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON ALL TABLES IN SCHEMA public FROM authenticated;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM authenticated;
    END IF;
END
$$;

COMMIT;
